export function cellById(id: string): Cell | undefined {
  return cells.find((cell) => cell.id === id);
}

export function sceneCells(): Cell[] {
  return cells
    .filter((cell): cell is Cell & { scene: NonNullable<Cell["scene"]> } =>
      cell.scene !== undefined,
    )
    .sort((a, b) => a.scene - b.scene);
}
